import { Building3D, ExportSettings, UrbanDataset } from '../../types';
import { buildBuildingGeometry } from '../geometryBuilder';
import { getUnitScale, transformPoint } from './unitUtils';

export function exportToFBX(
  dataset: UrbanDataset,
  settings: ExportSettings
): { fbx: string; filename: string } {
  const safeCityName = dataset.name.replace(/[^a-zA-Z0-9_-]/g, '_');
  const filename = `${safeCityName}_3D_Buildings.fbx`;

  const lines: string[] = [];

  // FBX Header
  lines.push('; FBX 7.4.0 project file');
  lines.push('; Generated by Geo3D Studio - Geospatial 3D Extractor');
  lines.push('; --------------------------------------------------');
  lines.push('');
  lines.push('FBXHeaderExtension:  {');
  lines.push('\tFBXHeaderVersion: 1003');
  lines.push('\tFBXVersion: 7400');
  lines.push('\tCreationTimeStamp:  {');
  lines.push('\t\tVersion: 1000');
  lines.push('\t\tYear: 2026');
  lines.push('\t\tMonth: 10');
  lines.push('\t\tDay: 26');
  lines.push('\t\tHour: 12');
  lines.push('\t\tMinute: 0');
  lines.push('\t\tSecond: 0');
  lines.push('\t\tMillisecond: 0');
  lines.push('\t}');
  lines.push('\tCreator: "Geo3D Studio v2.4"');
  lines.push('}');
  lines.push('');

  // Global Settings
  const upAxisVal = settings.upAxis === 'Z_UP' ? 2 : 1;
  const unitFactor = settings.units === 'millimeters' ? 1.0 : settings.units === 'feet' ? 30.48 : 100.0; // FBX standard is cm

  lines.push('GlobalSettings:  {');
  lines.push('\tVersion: 1000');
  lines.push('\tProperties70:  {');
  lines.push(`\t\tP: "UpAxis", "int", "Integer", "",${upAxisVal}`);
  lines.push('\t\tP: "UpAxisSign", "int", "Integer", "",1');
  lines.push('\t\tP: "FrontAxis", "int", "Integer", "",2');
  lines.push('\t\tP: "FrontAxisSign", "int", "Integer", "",1');
  lines.push('\t\tP: "CoordAxis", "int", "Integer", "",0');
  lines.push('\t\tP: "CoordAxisSign", "int", "Integer", "",1');
  lines.push(`\t\tP: "UnitScaleFactor", "double", "Number", "",${unitFactor}`);
  lines.push('\t}');
  lines.push('}');
  lines.push('');

  // Collect all vertex and polygon index data
  const allVertices: number[] = [];
  const allPolygonIndices: number[] = [];
  const allNormals: number[] = [];
  const allUVs: number[] = [];
  const allMaterials: number[] = [];

  let vertexOffset = 0;

  for (let b = 0; b < dataset.buildings.length; b++) {
    const building = dataset.buildings[b];
    const mesh = buildBuildingGeometry(building, settings.buildingHeightMultiplier);
    if (mesh.positions.length === 0) continue;

    const numVerts = mesh.positions.length / 3;

    // Transform vertices
    for (let i = 0; i < numVerts; i++) {
      const vx = mesh.positions[i * 3];
      const vy = mesh.positions[i * 3 + 1];
      const vz = mesh.positions[i * 3 + 2];
      const [tx, ty, tz] = transformPoint(vx, vy, vz, settings.upAxis, settings.units);
      allVertices.push(tx, ty, tz);

      const nx = mesh.normals[i * 3];
      const ny = mesh.normals[i * 3 + 1];
      const nz = mesh.normals[i * 3 + 2];
      const [tnx, tny, tnz] = transformPoint(nx, ny, nz, settings.upAxis, 'meters');
      allNormals.push(tnx, tny, tnz);

      allUVs.push(mesh.uvs[i * 2], mesh.uvs[i * 2 + 1]);
    }

    // Polygon indices (in FBX triangles: [v0, v1, ~v2])
    for (let t = 0; t < mesh.indices.length; t += 3) {
      const idx0 = vertexOffset + mesh.indices[t];
      const idx1 = vertexOffset + mesh.indices[t + 1];
      const idx2 = vertexOffset + mesh.indices[t + 2];

      allPolygonIndices.push(idx0, idx1, -idx2 - 1); // FBX negative termination
      allMaterials.push(0); // Material index 0
    }

    vertexOffset += numVerts;
  }

  // Objects section
  const geomId = 100000001;
  const modelId = 200000001;
  const matId = 300000001;

  lines.push('Objects:  {');
  lines.push(`\tGeometry: ${geomId}, "Geometry::Mesh", "Mesh" {`);
  lines.push(`\t\tVertices: *${allVertices.length} {`);
  lines.push(`\t\t\ta: ${allVertices.map(v => v.toFixed(3)).join(',')}`);
  lines.push('\t\t}');
  lines.push(`\t\tPolygonVertexIndex: *${allPolygonIndices.length} {`);
  lines.push(`\t\t\ta: ${allPolygonIndices.join(',')}`);
  lines.push('\t\t}');

  // LayerElementNormal
  lines.push('\t\tLayerElementNormal: 0 {');
  lines.push('\t\t\tVersion: 101');
  lines.push('\t\t\tName: ""');
  lines.push('\t\t\tMappingInformationType: "ByPolygonVertex"');
  lines.push('\t\t\tReferenceInformationType: "Direct"');
  lines.push(`\t\t\tNormals: *${allNormals.length} {`);
  lines.push(`\t\t\t\ta: ${allNormals.map(n => n.toFixed(3)).join(',')}`);
  lines.push('\t\t\t}');
  lines.push('\t\t}');

  // LayerElementMaterial
  lines.push('\t\tLayerElementMaterial: 0 {');
  lines.push('\t\t\tVersion: 101');
  lines.push('\t\t\tName: ""');
  lines.push('\t\t\tMappingInformationType: "AllSame"');
  lines.push('\t\t\tReferenceInformationType: "IndexToDirect"');
  lines.push('\t\t\tMaterials: *1 {');
  lines.push('\t\t\t\ta: 0');
  lines.push('\t\t\t}');
  lines.push('\t\t}');

  // Layer
  lines.push('\t\tLayer: 0 {');
  lines.push('\t\t\tVersion: 100');
  lines.push('\t\t\tLayerElement:  {');
  lines.push('\t\t\t\tType: "LayerElementNormal"');
  lines.push('\t\t\t\tTypedIndex: 0');
  lines.push('\t\t\t}');
  lines.push('\t\t\tLayerElement:  {');
  lines.push('\t\t\t\tType: "LayerElementMaterial"');
  lines.push('\t\t\t\tTypedIndex: 0');
  lines.push('\t\t\t}');
  lines.push('\t\t}');
  lines.push('\t}');

  // Model node
  lines.push(`\tModel: ${modelId}, "Model::${safeCityName}_3D", "Mesh" {`);
  lines.push('\t\tVersion: 232');
  lines.push('\t\tProperties70:  {');
  lines.push('\t\t\tP: "InheritType", "enum", "", "",1');
  lines.push('\t\t\tP: "ScalingMax", "Vector3D", "Vector", "",0,0,0');
  lines.push('\t\t\tP: "DefaultAttributeIndex", "int", "Integer", "",0');
  lines.push('\t\t}');
  lines.push('\t\tShading: T');
  lines.push('\t\tCulling: "CullingOff"');
  lines.push('\t}');

  // Material
  lines.push(`\tMaterial: ${matId}, "Material::ArchitecturalMat", "" {`);
  lines.push('\t\tVersion: 102');
  lines.push('\t\tShadingModel: "phong"');
  lines.push('\t\tProperties70:  {');
  lines.push('\t\t\tP: "DiffuseColor", "Color", "", "A",0.8,0.85,0.9');
  lines.push('\t\t\tP: "SpecularColor", "Color", "", "A",0.2,0.2,0.2');
  lines.push('\t\t\tP: "Shininess", "double", "Number", "",20.0');
  lines.push('\t\t}');
  lines.push('\t}');
  lines.push('}');
  lines.push('');

  // Connections
  lines.push('Connections:  {');
  lines.push(`\t;Model::${safeCityName}_3D, Model::RootNode`);
  lines.push(`\tC: "OO",${modelId},0`);
  lines.push(`\t;Geometry::Mesh, Model::${safeCityName}_3D`);
  lines.push(`\tC: "OO",${geomId},${modelId}`);
  lines.push(`\t;Material::ArchitecturalMat, Model::${safeCityName}_3D`);
  lines.push(`\tC: "OO",${matId},${modelId}`);
  lines.push('}');

  return {
    fbx: lines.join('\n'),
    filename,
  };
}
