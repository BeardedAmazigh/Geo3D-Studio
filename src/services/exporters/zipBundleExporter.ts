import JSZip from 'jszip';
import { ExportSettings, UrbanDataset } from '../../types';
import { exportToDXF } from './dxfExporter';
import { exportToFBX } from './fbxExporter';
import { exportToGLTF } from './gltfExporter';
import { exportToOBJ } from './objExporter';
import { exportToRVTWorkflow } from './rvtExporter';
import { exportToSKPWorkflow } from './skpExporter';
import { exportToSTL } from './stlExporter';

export async function exportToZIPBundle(
  dataset: UrbanDataset,
  settings: ExportSettings
): Promise<{ blob: Blob; filename: string }> {
  const zip = new JSZip();
  const safeCityName = dataset.name.replace(/[^a-zA-Z0-9_-]/g, '_');
  const zipFilename = `${safeCityName}_3D_CAD_BIM_Package.zip`;

  // 1. OBJ folder
  const objRes = exportToOBJ(dataset, settings);
  const objFolder = zip.folder('OBJ_Wavefront');
  objFolder?.file(objRes.filename, objRes.obj);
  objFolder?.file(`${safeCityName}_materials.mtl`, objRes.mtl);

  // 2. FBX folder
  const fbxRes = exportToFBX(dataset, settings);
  const fbxFolder = zip.folder('FBX_Autodesk');
  fbxFolder?.file(fbxRes.filename, fbxRes.fbx);

  // 3. DXF folder (AutoCAD / Rhino / Civil3D)
  const dxfRes = exportToDXF(dataset, settings);
  const dxfFolder = zip.folder('DXF_AutoCAD');
  dxfFolder?.file(dxfRes.filename, dxfRes.dxf);

  // 4. SketchUp (.SKP) folder
  const skpRes = exportToSKPWorkflow(dataset, settings);
  const skpFolder = zip.folder('SKP_SketchUp');
  skpFolder?.file(skpRes.filename, skpRes.dae);
  skpFolder?.file('import_to_skp.rb', skpRes.rubyScript);
  skpFolder?.file('SKETCHUP_IMPORT_GUIDE.md', skpRes.readme);

  // 5. Revit (.RVT) folder
  const rvtRes = exportToRVTWorkflow(dataset, settings);
  const rvtFolder = zip.folder('RVT_Revit_BIM');
  rvtFolder?.file(rvtRes.filename, rvtRes.ifc);
  rvtFolder?.file('revit_bim_automation.py', rvtRes.revitScript);
  rvtFolder?.file('REVIT_BIM_GUIDE.md', rvtRes.revitGuide);

  // 6. STL folder (3D Printing)
  const stlRes = exportToSTL(dataset, settings);
  const stlFolder = zip.folder('STL_3D_Printing');
  stlFolder?.file(stlRes.filename, stlRes.stl);

  // 7. glTF folder
  const gltfRes = exportToGLTF(dataset, settings);
  const gltfFolder = zip.folder('GLTF_Web_CESIUM');
  gltfFolder?.file(gltfRes.filename, gltfRes.gltf);

  // 8. 3D GeoJSON
  const geojsonObj = {
    type: 'FeatureCollection',
    name: dataset.name,
    features: dataset.buildings.map(b => ({
      type: 'Feature',
      properties: {
        id: b.id,
        name: b.name,
        height: b.height,
        levels: b.levels,
        roofShape: b.roofShape,
        typology: b.typology,
        areaM2: b.areaMeters2,
        address: b.address,
        tags: b.tags,
      },
      geometry: {
        type: 'Polygon',
        coordinates: [
          b.geoFootprint || b.footprint.map(p => [dataset.center[1] + p[0] * 0.00001, dataset.center[0] + p[1] * 0.00001]),
        ],
      },
    })),
  };
  zip.file(`${safeCityName}_3D_Buildings.geojson`, JSON.stringify(geojsonObj, null, 2));

  // 9. Root Master Documentation
  const masterReadme = `# ${dataset.name} - 3D Urban Model & CAD/BIM Export Bundle
Generated by Geo3D Studio - Geospatial 3D Extractor

## Dataset Details
- Location: ${dataset.name}
- Center Coordinates: Lat ${dataset.center[0].toFixed(5)}, Lon ${dataset.center[1].toFixed(5)}
- Radius: ${dataset.radiusMeters}m
- Total Buildings: ${dataset.buildings.length}
- Target Units: ${settings.units}
- Up-Axis: ${settings.upAxis}
- Source: ${dataset.source}

## Folder Structure
- /OBJ_Wavefront: Universal 3D geometry with .mtl materials (Blender, Maya, 3ds Max, Rhino)
- /FBX_Autodesk: Standard Autodesk FBX 7.4 with node hierarchy & normals
- /DXF_AutoCAD: 3DFACE and 3D Polylines with height-layered strata (AutoCAD, Civil 3D, Rhino)
- /SKP_SketchUp: Native Collada .dae + SketchUp automated ruby script
- /RVT_Revit_BIM: Industry Foundation Classes IFC 2x3 + Model-by-Face conversion manual
- /STL_3D_Printing: Manifold triangles for scale model 3D printing
- /GLTF_Web_CESIUM: Modern glTF 2.0 asset for WebGL, Cesium, and spatial computing
- *.geojson: Full 3D GeoJSON GIS boundary vectors and metadata
`;
  zip.file('README_CAD_BIM_IMPORT.md', masterReadme);

  const blob = await zip.generateAsync({ type: 'blob' });
  return { blob, filename: zipFilename };
}
